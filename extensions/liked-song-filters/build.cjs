// A single dependency-free artifact works with both CLI installs and Marketplace.
const fs = require("node:fs");
const path = require("node:path");
const root = __dirname;
const { version } = require("./package.json");
function bundle(name) {
  return `(() => { const module = { exports: {} };\n${fs.readFileSync(path.join(root, "src", name + ".js"), "utf8")}\nreturn module.exports; })()`;
}
const output = `// NAME: Liked Song Filters\n// VERSION: ${version}\n// DESCRIPTION: Save genre, mood, and audio-feature filters for Liked Songs.\n// Generated by node build.cjs; edit src/ instead.\n(function () {\n"use strict";\nconst core = ${bundle("core")};\nconst { createStore } = ${bundle("storage")};\nconst { mountPanel } = ${bundle("panel")};\nconst { createExtension } = ${bundle("lifecycle")};\ncreateExtension(window, { core, createStore, mountPanel, version: ${JSON.stringify(version)} });\n})();\n`;
fs.mkdirSync(path.join(root, "dist"), { recursive: true });
fs.writeFileSync(path.join(root, "dist/liked-song-filters.js"), output);
console.log(`Built liked-song-filters.js ${version}`);
